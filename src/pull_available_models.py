#!/usr/bin/env python3
"""Render reviewed offers offline; optionally refresh the public OpenRouter catalog."""

import argparse
from datetime import datetime, timezone
from decimal import Decimal, InvalidOperation
import json
from pathlib import Path
import re
import shutil
import tempfile
from urllib.parse import quote
from urllib.request import urlopen

from providers import PROVIDERS, REVIEW_DATE, SECTIONS

SCRIPT_DIR = Path(__file__).resolve().parent
CATALOG_PATH = SCRIPT_DIR / "openrouter_models.json"
CATALOG_URL = "https://openrouter.ai/api/v1/models"
WARNING = "<!---\nWARNING: DO NOT EDIT THIS FILE DIRECTLY. IT IS GENERATED BY src/pull_available_models.py\n--->\n"


def select_free_models(payload):
    """Fail closed: missing, negative or malformed prices never establish free usage."""
    if not isinstance(payload, dict) or not isinstance(payload.get("data"), list):
        raise ValueError("Unexpected OpenRouter catalog response")
    selected = {}
    for model in payload["data"]:
        if not isinstance(model, dict):
            continue
        model_id = model.get("id")
        if not isinstance(model_id, str) or not model_id.endswith(":free"):
            continue
        pricing = model.get("pricing")
        if not isinstance(pricing, dict):
            continue
        try:
            prices = [Decimal(str(pricing[key])) for key in ("prompt", "completion")]
        except (KeyError, InvalidOperation):
            continue
        if not all(price.is_finite() and price == 0 for price in prices):
            continue
        name = model.get("name")
        selected[model_id] = {
            "id": model_id,
            "name": name if isinstance(name, str) and name else model_id,
        }
    return sorted(selected.values(), key=lambda model: (model["name"].lower(), model["id"]))


def fetch_catalog():
    # Only a public metadata GET; no credentials or inference requests are needed.
    with urlopen(CATALOG_URL, timeout=30) as response:
        models = select_free_models(json.load(response))
    if not models:
        raise ValueError("No free models returned; keep the snapshot and review the provider")
    return {
        "source": CATALOG_URL,
        "retrieved_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "models": models,
    }


def write_outputs(outputs):
    """Stage all output and backups first; restore earlier replacements on failure."""
    staged = []
    replaced = []
    directories = []
    retain_backups = False
    try:
        for target, text in outputs.items():
            directory = Path(tempfile.mkdtemp(prefix=".readme-", dir=target.parent))
            directories.append(directory)
            replacement = directory / "new"
            replacement.write_text(text, encoding="utf-8")
            backup = None
            if target.exists():
                backup = directory / "old"
                shutil.copy2(target, backup)
                shutil.copymode(target, replacement)
            staged.append((target, replacement, backup))
        try:
            for target, replacement, backup in staged:
                replacement.replace(target)
                replaced.append((target, backup))
        except OSError as error:
            rollback_errors = []
            for target, backup in reversed(replaced):
                try:
                    if backup is None:
                        target.unlink()
                    else:
                        backup.replace(target)
                except OSError as rollback_error:
                    rollback_errors.append(str(rollback_error))
            if rollback_errors:
                retain_backups = True
                locations = ", ".join(str(directory) for directory in directories)
                raise RuntimeError(
                    f"Output update and rollback failed; recovery files retained in {locations}: "
                    + "; ".join(rollback_errors)
                ) from error
            raise
    finally:
        if not retain_backups:
            for directory in directories:
                shutil.rmtree(directory)


def load_catalog(path=CATALOG_PATH):
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def markdown_text(value):
    return re.sub(r"([\\`*\[\]<>_])", r"\\\1", " ".join(value.split()))


def generate_toc(markdown):
    toc = []
    for hashes, title in re.findall(r"^(#{2,3}) +(.+)", markdown, re.MULTILINE):
        display = re.sub(r"\[(.*?)\]\([^)]*\)", r"\1", title)
        anchor = re.sub(r"[^a-z0-9 _-]", "", display.lower()).replace(" ", "-")
        indent = "  " if len(hashes) == 3 else ""
        toc.append(f"{indent}- [{display}](#{anchor})")
    return "\n".join(toc)


def render_catalog(snapshot):
    if snapshot is None:
        return "See the official model catalog linked above for current free models.\n"
    lines = [
        "<details>", "<summary>OpenRouter free model snapshot</summary>", "",
        f"Metadata retrieved at **{snapshot['retrieved_at']}**. This is a catalog snapshot, not an inference availability test.", "",
    ]
    for model in snapshot["models"]:
        url = "https://openrouter.ai/" + quote(model["id"], safe="/:")
        lines.append(f"- [{markdown_text(model['name'])}]({url})")
    return "\n".join(lines + ["", "</details>", ""])


def render_readme(template, snapshot=None):
    sections = []
    for category, (title, introduction) in SECTIONS.items():
        sections.extend([f"## {title}", "", introduction, ""])
        for provider in PROVIDERS:
            if provider["category"] != category:
                continue
            sources = " · ".join(f"[{label}]({url})" for label, url in provider["sources"])
            review_label = "Last checked; offer unconfirmed" if category == "unverified" else "Last reviewed"
            sections.extend([
                f"### [{provider['name']}]({provider['url']})", "",
                f"**Offer:** {provider['offer']}", "",
                f"**Conditions:** {provider['conditions']}", "",
                f"**Official sources:** {sources}", "",
                f"**{review_label}:** {provider.get('reviewed_on', REVIEW_DATE)}", "",
            ])
            if provider["id"] == "openrouter":
                sections.extend([render_catalog(snapshot), ""])
    readme = WARNING + template.replace("{{REVIEW_DATE}}", REVIEW_DATE).replace("{{PROVIDER_SECTIONS}}", "\n".join(sections).rstrip())
    return readme.replace("{{TOC}}", generate_toc(readme))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-models", action="store_true", help="Refresh public OpenRouter metadata before rendering (network required)")
    parser.add_argument("--check", action="store_true", help="Check the committed README against local sources without writing")
    args = parser.parse_args()
    if args.check and args.refresh_models:
        parser.error("--check is offline; run --refresh-models separately")
    template = (SCRIPT_DIR / "README_template.md").read_text(encoding="utf-8")
    snapshot = fetch_catalog() if args.refresh_models else load_catalog(CATALOG_PATH)
    readme = render_readme(template, snapshot)
    output = SCRIPT_DIR.parent / "README.md"
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != readme:
            parser.exit(1, "README.md is out of date; run python src/pull_available_models.py\n")
        print("README.md matches the reviewed sources and catalog snapshot")
    else:
        outputs = {}
        if args.refresh_models:
            outputs[CATALOG_PATH] = json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n"
        outputs[output] = readme
        write_outputs(outputs)
        print("Wrote README.md")


if __name__ == "__main__":
    main()
